// 一時: rules.js の段落正規化（normalizeParagraph）の回帰確認
//
// 「公用文作成の考え方」Ⅰ-6 の階層見出しと、原典PDFに現れる構造マーカー
// （〔設問〕【資料】）が、句点の直後で正しく改行されるかを確かめる。
// 使い方: node scripts/_probe.mjs
import { normalizeParagraph, mergeBrokenParagraphs } from "../rules.js";

let ng = 0;
const ok = (cond, label) => {
  console.log(`${cond ? "OK " : "NG "} ${label}`);
  if (!cond) ng++;
};
const split = (s) => normalizeParagraph(s).join("|");

ok(
  split("大きく下回ることとなった。〔設 問〕Ｘ社の行為について") ===
    "大きく下回ることとなった。|〔設 問〕Ｘ社の行為について",
  "〔設 問〕で分割",
);
ok(
  split("と反論した。〔設問１⑴〕") === "と反論した。|〔設問１⑴〕",
  "〔設問１⑴〕で分割",
);
ok(
  split("求めるものである。【Ｓ市都市計画課の会議録】において示唆した") ===
    "求めるものである。|【Ｓ市都市計画課の会議録】において示唆した",
  "【…】で分割",
);

// 句点を挟まない連続見出しは分割対象外（原典の字送り情報が無く判別できない）
ok(
  normalizeParagraph("第３ 採点実感等１ 第１問について").length === 1,
  "句点が無ければ分割しない",
);
// 丸数字は階層表に無く、「①については」のような文中参照でも使われる
ok(
  normalizeParagraph("可否である。①については").length === 1,
  "丸数字①は分割しない",
);
ok(normalizeParagraph("という。〔以下省略〕").length === 2, "短い〔…〕でも分割");
// 〔…〕が長い場合は見出しではなく引用・注記とみなす
ok(
  normalizeParagraph("である。〔" + "あ".repeat(20) + "〕").length === 1,
  "長すぎる〔…〕は見出し扱いしない",
);

// ─── 改ページ等で分断された段落の結合 ───────────────────────────────────
const merge = (a) => mergeBrokenParagraphs(a).join("|");

ok(
  merge(["その変動はなかったもの", "とする。また、考慮しない。"]) ===
    "その変動はなかったものとする。また、考慮しない。",
  "文の途中で切れた段落を結合",
);
ok(
  merge(["請求３が認められる", "か、論じなさい。"]) ===
    "請求３が認められるか、論じなさい。",
  "「か、」で始まる続きを結合",
);
// 見出しは文末記号が無くても次の段落の続きではない
ok(
  merge(["４ 法科大学院教育に求めるもの", "このような結果を踏まえると、"]) ===
    "４ 法科大学院教育に求めるもの|このような結果を踏まえると、",
  "見出しの次は結合しない",
);
ok(
  merge(["〔設問１〕", "なさい。"]) === "〔設問１〕|なさい。",
  "設問見出しの次は結合しない",
);
ok(
  merge(["問いに答えなさい。", "このような場合"]) ===
    "問いに答えなさい。|このような場合",
  "文末で終わっていれば結合しない",
);

// ─── 出題の趣旨の科目セクションの切り出し ───────────────────────────────
const { parseShushiSection, parseShushiSectionSelect } = await import(
  "../parser.js"
);
// 行ごとに1ボックスの疑似 PDF（y は上から下へ）
const boxes = (lines) =>
  lines.map((text, i) => ({
    text,
    x0: 0,
    x1: 100,
    y0: -i * 10,
    y1: -i * 10 + 9,
    page: 1,
  }));

// 合冊PDFでは系科目の後ろに選択科目が続く（平成28年など）
const sec = parseShushiSection(
  boxes([
    "【刑事系科目】",
    "〔第２問〕",
    "本問は，捜査に関する事例である。",
    "倒産法",
    "〔第１問〕",
    "本問は，破産手続の事例である。",
  ]),
  "刑事系科目",
  2,
).paras.join("");
ok(!sec.includes("破産"), "系科目が後続の選択科目を取り込まない");

// 扉行を拾えなくても、問番号が第２問から第１問へ戻れば別科目とみなす
const sec2 = parseShushiSection(
  boxes([
    "【刑事系科目】",
    "〔第２問〕",
    "本問は，捜査に関する事例である。",
    "〔第１問〕",
    "本問は，破産手続の事例である。",
  ]),
  "刑事系科目",
  2,
).paras.join("");
ok(!sec2.includes("破産"), "問番号が戻ったら別科目として打ち切る");

// 科目名がテキスト抽出で複数の片に分かれる場合
const sel = parseShushiSectionSelect(
  boxes([
    "国際関係法",
    "（公法系）",
    "〔第１問〕",
    "本問は，国家承認を問う。",
    "労働法",
    "〔第１問〕",
    "本問は，解雇を問う。",
  ]),
  "国際関係法（公法系）",
  1,
).paras.join("");
ok(
  sel.includes("国家承認") && !sel.includes("解雇"),
  "分割された科目名でも見出しを照合",
);

// 自科目の見出しが無い合冊PDFは、別科目を先頭から取り込まず失敗させる
let threw = false;
try {
  parseShushiSectionSelect(
    boxes(["憲法", "〔第１問〕", "本問は，貧困と権利である。", "労働法"]),
    "租税法",
    1,
  );
} catch {
  threw = true;
}
ok(threw, "自科目の見出しが無い合冊PDFは失敗させる");

// 見出しの無い個別PDFは従来どおり先頭から
ok(
  parseShushiSectionSelect(
    boxes(["〔第１問〕", "本問は，所得区分を問う。"]),
    "租税法",
    1,
  )
    .paras.join("")
    .includes("所得区分"),
  "見出しの無い個別PDFは先頭から",
);

// 本文中に出てくる科目名でセクションを打ち切らない
ok(
  parseShushiSection(
    boxes([
      "【民事系科目】",
      "〔第１問〕",
      "本問は，知的財産法の議論も参照する会社法の事例である。",
      "【刑事系科目】",
      "〔第１問〕",
      "本問は，殺人の事例である。",
    ]),
    "民事系科目",
    1,
  )
    .paras.join("")
    .includes("会社法"),
  "本文中の科目名では打ち切らない",
);

console.log(ng === 0 ? "\n全テストOK" : `\nNG ${ng}件`);
process.exit(ng ? 1 : 0);
