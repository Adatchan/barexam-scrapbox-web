// 段落構造まわりの回帰テスト（外部依存なしで動く）
//
//   ・rules.js の段落正規化: 「公用文作成の考え方」Ⅰ-6 の階層見出しと、
//     原典PDFに現れる構造マーカー（〔設問〕【資料】）を句点の直後で改行する。
//   ・rules.js の段落結合: 改ページで文の途中に入った区切りを繋ぎ直す。
//   ・parser.js のセクション切り出し: 合冊PDFで別科目を取り込まない。
//
// 使い方: node scripts/test-rules.mjs
import { normalizeParagraph, mergeBrokenParagraphs } from "../rules.js";

let ng = 0;
const ok = (cond, label) => {
  console.log(`${cond ? "OK " : "NG "} ${label}`);
  if (!cond) ng++;
};
const split = (s) => normalizeParagraph(s).join("|");

ok(
  split("大きく下回ることとなった。〔設 問〕Ｘ社の行為について") ===
    "大きく下回ることとなった。|〔設 問〕Ｘ社の行為について",
  "〔設 問〕で分割",
);
ok(
  split("と反論した。〔設問１⑴〕") === "と反論した。|〔設問１⑴〕",
  "〔設問１⑴〕で分割",
);
ok(
  split("求めるものである。【Ｓ市都市計画課の会議録】において示唆した") ===
    "求めるものである。|【Ｓ市都市計画課の会議録】において示唆した",
  "【…】で分割",
);

// 句点を挟まない連続見出しは分割対象外（原典の字送り情報が無く判別できない）
ok(
  normalizeParagraph("第３ 採点実感等１ 第１問について").length === 1,
  "句点が無ければ分割しない",
);
// 丸数字は階層表に無く、「①については」のような文中参照でも使われる
ok(
  normalizeParagraph("可否である。①については").length === 1,
  "丸数字①は分割しない",
);
ok(normalizeParagraph("という。〔以下省略〕").length === 2, "短い〔…〕でも分割");
// 〔…〕が長い場合は見出しではなく引用・注記とみなす
ok(
  normalizeParagraph("である。〔" + "あ".repeat(20) + "〕").length === 1,
  "長すぎる〔…〕は見出し扱いしない",
);

// ─── 改ページ等で分断された段落の結合 ───────────────────────────────────
const merge = (a) => mergeBrokenParagraphs(a).join("|");

ok(
  merge(["その変動はなかったもの", "とする。また、考慮しない。"]) ===
    "その変動はなかったものとする。また、考慮しない。",
  "文の途中で切れた段落を結合",
);
ok(
  merge(["請求３が認められる", "か、論じなさい。"]) ===
    "請求３が認められるか、論じなさい。",
  "「か、」で始まる続きを結合",
);
// 見出しは文末記号が無くても次の段落の続きではない
ok(
  merge(["４ 法科大学院教育に求めるもの", "このような結果を踏まえると、"]) ===
    "４ 法科大学院教育に求めるもの|このような結果を踏まえると、",
  "見出しの次は結合しない",
);
ok(
  merge(["〔設問１〕", "なさい。"]) === "〔設問１〕|なさい。",
  "設問見出しの次は結合しない",
);
ok(
  merge(["問いに答えなさい。", "このような場合"]) ===
    "問いに答えなさい。|このような場合",
  "文末で終わっていれば結合しない",
);

const { parseShushiSection, parseShushiSectionSelect, mergeOverlaidPunctuation } =
  await import("../parser.js");

// ─── 構造マーカー行の判定 ───────────────────────────────────────────────
const { STRUCTURE_MARKER_RE } = await import("../rules.js");
ok(STRUCTURE_MARKER_RE.test("第３ 採点実感等"), "「第３ …」は構造マーカー");
ok(STRUCTURE_MARKER_RE.test("１ 出題の趣旨"), "「１ …」は構造マーカー");
ok(STRUCTURE_MARKER_RE.test("１．出題の趣旨"), "「１．…」は構造マーカー");
ok(
  !STRUCTURE_MARKER_RE.test("3.5：1.5：3.5：1.5〕）社団法人Ａは，"),
  "配点の小数は構造マーカーではない",
);

// ─── 会話文の開始行の判定 ───────────────────────────────────────────────
const { DIALOGUE_RE } = await import("../rules.js");
ok(DIALOGUE_RE.test("甲：それでは，"), "「甲：」は会話文の開始");
// 話者名は4文字までしか見ない（「弁護士Ｌ１：」のような長い名前は対象外）
ok(DIALOGUE_RE.test("Ｌ１：まず，"), "「Ｌ１：」は会話文の開始");
ok(!DIALOGUE_RE.test("注：以下略"), "「注：」は注記ラベル");
ok(
  !DIALOGUE_RE.test("３０：１５〕）株式会社Ａは，"),
  "配点の比（全角）は会話文ではない",
);
ok(
  !DIALOGUE_RE.test("3.5：1.5：3.5：1.5〕）社団法人Ａは，"),
  "配点の比（半角小数）は会話文ではない",
);

// ─── 行に重ねて描かれた句読点の差し込み ─────────────────────────────────
// 座標は実際のPDF（令和６年 倒産法 採点実感）から採った値
const item = (x, width, text) => ({ x, width, height: 10, y: 0, text });
const line = (items) => {
  const r = mergeOverlaidPunctuation(items);
  r.sort((a, b) => a.x - b.x);
  return r
    .map((it) => it.text)
    .join("")
    .trim();
};

ok(
  line([
    item(
      111.7,
      412.6,
      "設問１は、役員の財産に対する保全処分の申立て（破産法第１７７条第１項 、役員の責任",
    ),
    item(458.2, 10, "）"),
  ]) ===
    "設問１は、役員の財産に対する保全処分の申立て（破産法第１７７条第１項）、役員の責任",
  "重ねて描かれた閉じ括弧を元の桁に戻す",
);
ok(
  line([
    item(
      81.0,
      443.3,
      "権についての定め（設問１ 、再生債権の査定に関する定め（設問２ 、双方未履行の双務契約の解",
    ),
    item(201.8, 10, "）"),
    item(211.8, 176.5, " "),
    item(388.3, 10, "）"),
  ]) ===
    "権についての定め（設問１）、再生債権の査定に関する定め（設問２）、双方未履行の双務契約の解",
  "同じ行に2つ戻し、隙間を埋める空白項目は捨てる",
);
ok(
  line([
    item(
      111.7,
      412.6,
      "要件の検討をしている答案においては、保全処分の申立ての要件のうち 「必要があると認",
    ),
    item(437.8, 10, "、"),
  ]) ===
    "要件の検討をしている答案においては、保全処分の申立ての要件のうち、「必要があると認",
  "重ねて描かれた読点を元の桁に戻す",
);
ok(
  line([item(81, 200, "通常の行であって"), item(281, 100, "重なりはない。")]) ===
    "通常の行であって重なりはない。",
  "重なりの無い行は素通りする",
);
ok(
  line([item(81, 200, "空白のない本文である"), item(120, 10, "。")]) ===
    "空白のない本文である。",
  "桁に空白が無ければ元の位置が分からないので従来どおり",
);

// ─── 次の行へ続く配点の注記 ─────────────────────────────────────────────
const { bracketDepth, closeIndex } = await import("../parser.js");
{
  const head =
    "〔第２問〕（配点：１００〔〔設問１〕，〔設問２〕（１），〔設問２〕（２），〔設問３〕の配点の割合は，";
  const next = "3.5：1.5：3.5：1.5〕）社団法人Ａは，モーターボート競走の";
  const cut = closeIndex(next, bracketDepth(head));
  ok(
    head + next.slice(0, cut) ===
      "〔第２問〕（配点：１００〔〔設問１〕，〔設問２〕（１），〔設問２〕（２），〔設問３〕の配点の割合は，3.5：1.5：3.5：1.5〕）",
    "次の行へ続く配点の注記を見出しに取り込む",
  );
  ok(
    next.slice(cut) === "社団法人Ａは，モーターボート競走の",
    "注記の後ろは本文として残す",
  );
}
ok(bracketDepth("〔第１問〕（配点：１００）") === 0, "閉じた見出しは取り込まない");

// ─── 出題の趣旨の科目セクションの切り出し ───────────────────────────────
// 行ごとに1ボックスの疑似 PDF（y は上から下へ）
const boxes = (lines) =>
  lines.map((text, i) => ({
    text,
    x0: 0,
    x1: 100,
    y0: -i * 10,
    y1: -i * 10 + 9,
    page: 1,
  }));

// 合冊PDFでは系科目の後ろに選択科目が続く（平成28年など）
const sec = parseShushiSection(
  boxes([
    "【刑事系科目】",
    "〔第２問〕",
    "本問は，捜査に関する事例である。",
    "倒産法",
    "〔第１問〕",
    "本問は，破産手続の事例である。",
  ]),
  "刑事系科目",
  2,
).paras.join("");
ok(!sec.includes("破産"), "系科目が後続の選択科目を取り込まない");

// 扉行を拾えなくても、問番号が第２問から第１問へ戻れば別科目とみなす
const sec2 = parseShushiSection(
  boxes([
    "【刑事系科目】",
    "〔第２問〕",
    "本問は，捜査に関する事例である。",
    "〔第１問〕",
    "本問は，破産手続の事例である。",
  ]),
  "刑事系科目",
  2,
).paras.join("");
ok(!sec2.includes("破産"), "問番号が戻ったら別科目として打ち切る");

// 科目名がテキスト抽出で複数の片に分かれる場合
const sel = parseShushiSectionSelect(
  boxes([
    "国際関係法",
    "（公法系）",
    "〔第１問〕",
    "本問は，国家承認を問う。",
    "労働法",
    "〔第１問〕",
    "本問は，解雇を問う。",
  ]),
  "国際関係法（公法系）",
  1,
).paras.join("");
ok(
  sel.includes("国家承認") && !sel.includes("解雇"),
  "分割された科目名でも見出しを照合",
);

// 扉行が本文と同じ片にまとまっている場合
const sel2 = parseShushiSectionSelect(
  boxes([
    "憲法",
    "〔第１問〕",
    "本問は，貧困と権利である。",
    "［租 税 法］租税法の出題に関しては，基本的な理解を問うている。",
    "〔第１問〕",
    "本問は，所得区分を問う。",
    "［経 済 法］",
  ]),
  "租税法",
  1,
).paras.join("");
ok(
  sel2.includes("所得区分") && !sel2.includes("貧困"),
  "扉行が本文と同じ片でも見出しとして扱う",
);

// 科目名で始まる本文は見出しとみなさない
let threwBody = false;
try {
  parseShushiSectionSelect(
    boxes(["憲法", "〔第１問〕", "租税法上の所得区分が争われた事案である。"]),
    "租税法",
    1,
  );
} catch {
  threwBody = true;
}
ok(threwBody, "科目名で始まる本文は見出しとみなさない");

// 自科目の見出しが無い合冊PDFは、別科目を先頭から取り込まず失敗させる
let threw = false;
try {
  parseShushiSectionSelect(
    boxes(["憲法", "〔第１問〕", "本問は，貧困と権利である。", "労働法"]),
    "租税法",
    1,
  );
} catch {
  threw = true;
}
ok(threw, "自科目の見出しが無い合冊PDFは失敗させる");

// 見出しの無い個別PDFは従来どおり先頭から
ok(
  parseShushiSectionSelect(
    boxes(["〔第１問〕", "本問は，所得区分を問う。"]),
    "租税法",
    1,
  )
    .paras.join("")
    .includes("所得区分"),
  "見出しの無い個別PDFは先頭から",
);

// 本文中に出てくる科目名でセクションを打ち切らない
ok(
  parseShushiSection(
    boxes([
      "【民事系科目】",
      "〔第１問〕",
      "本問は，知的財産法の議論も参照する会社法の事例である。",
      "【刑事系科目】",
      "〔第１問〕",
      "本問は，殺人の事例である。",
    ]),
    "民事系科目",
    1,
  )
    .paras.join("")
    .includes("会社法"),
  "本文中の科目名では打ち切らない",
);

console.log(ng === 0 ? "\n全テストOK" : `\nNG ${ng}件`);
process.exit(ng ? 1 : 0);
