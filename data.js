// 科目 → [系列名, 問番号, 表示ラベル, 選択科目キーワード(任意)]
export const SUBJECT_MAP = {
  憲法: ["公法系科目", 1, "公法系第１問（憲法）"],
  行政法: ["公法系科目", 2, "公法系第２問（行政法）"],
  民法: ["民事系科目", 1, "民事系第１問（民法）"],
  商法: ["民事系科目", 2, "民事系第２問（商法）"],
  民訴: ["民事系科目", 3, "民事系第３問（民事訴訟法）"],
  刑法: ["刑事系科目", 1, "刑事系第１問（刑法）"],
  刑訴: ["刑事系科目", 2, "刑事系第２問（刑事訴訟法）"],
  // 選択科目は司法試験法施行規則第一条の掲名順（倒産法→…→国際関係法（私法系））。
  // 下の SELECT_SUBJECTS から第１問・第２問の2件ずつを機械的に展開する。
};

// 年度による例外。平成22年の民事系科目は2問構成で、第１問が商法（会社法）、
// 第２問が民法・民事訴訟法の総合問題（第３問は無い）。平成23年以降の
// 第１問=民法・第２問=商法・第３問=民訴とは並びが違うため、この年度だけ
// 差し替える。採点実感は科目別（民法／商法／民事訴訟法）に公表されるので、
// 表示ラベルの科目名は各科目のままにしておく（タイトル照合に使うため）。
const SUBJECT_MAP_BY_YEAR = {
  h22: {
    商法: ["民事系科目", 1, "民事系第１問（商法）"],
    民法: ["民事系科目", 2, "民事系第２問（民法）"],
    民訴: ["民事系科目", 2, "民事系第２問（民事訴訟法）"],
  },
};

// 年度・科目に対応する定義を返す（年度の例外があればそれを優先）。
export function subjectInfo(yearKey, subject) {
  return SUBJECT_MAP_BY_YEAR[yearKey]?.[subject] || SUBJECT_MAP[subject];
}

export const Q_KANJI = { 1: "１", 2: "２", 3: "３" };

// 選択科目（司法試験法施行規則第一条に掲げる8科目・掲名順）
export const SELECT_SUBJECTS = [
  "倒産法",
  "租税法",
  "経済法",
  "知的財産法",
  "労働法",
  "環境法",
  "国際関係法（公法系）",
  "国際関係法（私法系）",
];

// 選択科目は8科目 × 第１問・第２問を機械的に展開する（科目名だけが違い、
// 系列名・問番号・キーワードの作り方は共通のため）。
for (const name of SELECT_SUBJECTS) {
  for (const q of [1, 2]) {
    SUBJECT_MAP[`${name}第${Q_KANJI[q]}問`] = [
      "選択科目",
      q,
      `選択科目（${name}）第${Q_KANJI[q]}問`,
      name,
    ];
  }
}

// 科目名 → 系統（科目プルダウンの背景色分け用）。公法系・民事系・刑事系の
// 基本科目だけを色分けし、選択科目・法律実務基礎科目・一般教養科目など系統に
// 属さないものは null（無地）。司法・予備、論文・短答の全プルダウンで共用する。
export function subjectSystem(name) {
  if (/^(?:憲法|行政法)/.test(name)) return "public";
  if (/^(?:民法|商法|民訴|民事訴訟法)/.test(name)) return "civil";
  if (/^(?:刑法|刑訴|刑事訴訟法)/.test(name)) return "criminal";
  return null; // 選択科目・法律実務基礎科目・一般教養科目 など
}

// 系統 → プルダウン option の背景色（文字が読めるよう淡色にする）
export const SYSTEM_BG = {
  public: "#e6f4ea", // 公法系: 緑系
  civil: "#fce8e6", // 民事系: 赤系
  criminal: "#e8f0fe", // 刑事系: 青系
};

// 年度キー（"r7" / "h22"）→ 表示ラベル（"令和7年(2025年)" / "平成22年(2010年)"）
export function yearKeyToLabel(key) {
  const n = parseInt(key.slice(1), 10);
  if (key.startsWith("r")) {
    return `令和${n}年(${2018 + n}年)`;
  }
  return `平成${n}年(${1988 + n}年)`;
}
